// Rigid alpha/PCA normalization only. No generative editing, redrawing, or
// hook straightening. Originals and the front frame are never overwritten.
import { chromium } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { measureTempleAlpha } from '../src/components/tryon/templeAssetGeometry.js';
const root = new URL('../public/assets/products/eyewear/modern-clear-frame/', import.meta.url);
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage();
  const sources = await Promise.all(
    ['left', 'right'].map(
      async (side) =>
        `data:image/png;base64,${(await readFile(new URL(`modern-clear-${side}-temple.png`, root))).toString('base64')}`,
    ),
  );
  const results = await page.evaluate(
    async ({ sources, measureSource }) => {
      const measure = new Function(`return (${measureSource})`)();
      const canvas = (w, h) =>
        Object.assign(document.createElement('canvas'), { width: w, height: h });
      const inspect = (c, left) =>
        measure(
          c.getContext('2d').getImageData(0, 0, c.width, c.height).data,
          c.width,
          c.height,
          left,
        );
      return Promise.all(
        sources.map(async (src, i) => {
          const left = i === 0;
          const image = new Image();
          image.src = src;
          await image.decode();
          const source = canvas(image.width, image.height);
          source.getContext('2d').drawImage(image, 0, 0);
          const original = inspect(source, left);
          const angle = (-original.axisDegrees * Math.PI) / 180;
          const c = Math.cos(angle),
            s = Math.sin(angle);
          const rotated = canvas(
            Math.ceil(Math.abs(image.width * c) + Math.abs(image.height * s)) + 4,
            Math.ceil(Math.abs(image.width * s) + Math.abs(image.height * c)) + 4,
          );
          const ctx = rotated.getContext('2d');
          ctx.translate(rotated.width / 2, rotated.height / 2);
          ctx.rotate(angle);
          ctx.imageSmoothingEnabled = true;
          ctx.imageSmoothingQuality = 'high';
          ctx.drawImage(image, -image.width / 2, -image.height / 2);
          const b = inspect(rotated, left).bounds;
          const out = canvas(b.width, b.height);
          out.getContext('2d').drawImage(rotated, -b.x, -b.y);
          const point = (p) => ({
            x: rotated.width / 2 + (p.x - image.width / 2) * c - (p.y - image.height / 2) * s - b.x,
            y:
              rotated.height / 2 + (p.x - image.width / 2) * s + (p.y - image.height / 2) * c - b.y,
          });
          // Preserve the anatomical product endpoints from the original alpha mask.
          // Re-finding extrema after rotation would mistake a hinge corner for its centre.
          const normalized = {
            ...inspect(out, left),
            hinge: point(original.hinge),
            tip: point(original.tip),
          };
          normalized.visibleLength = Math.hypot(
            normalized.tip.x - normalized.hinge.x,
            normalized.tip.y - normalized.hinge.y,
          );
          normalized.hingeTipDegrees =
            (Math.atan2(
              normalized.tip.y - normalized.hinge.y,
              Math.abs(normalized.tip.x - normalized.hinge.x),
            ) *
              180) /
            Math.PI;
          normalized.hingePivot = {
            x: normalized.hinge.x / out.width,
            y: normalized.hinge.y / out.height,
          };
          return { original, normalized, png: out.toDataURL('image/png').split(',')[1] };
        }),
      );
    },
    { sources, measureSource: measureTempleAlpha.toString() },
  );
  const calibration = {};
  for (const [i, side] of ['left', 'right'].entries()) {
    const file = `modern-clear-${side}-temple-normalized.png`;
    await writeFile(new URL(`${side}-temple.png`, root), Buffer.from(results[i].png, 'base64'));
    const { png, ...measurements } = results[i];
    calibration[file] = measurements;
    console.log(JSON.stringify({ file, ...measurements }));
  }
  await writeFile(
    new URL('../src/data/modernClearTempleCalibration.js', import.meta.url),
    `// Generated by scripts/normalize-modern-clear-temples.mjs; rigid alpha/PCA measurements.\nexport const modernClearTempleCalibration = ${JSON.stringify(calibration, null, 2)};\n`,
  );
} finally {
  await browser.close();
}
